    protected $fillable = [
        'name',
        'sort_order',
        'is_active',
    ];

    protected function casts(): array
    {
        return [
            'sort_order' => 'integer',
            'is_active' => 'boolean',
        ];
    }

    /**
     * @return list<array{id: int, value: string, label: string}>
     */
    public static function options(): array
    {
        return static::query()
            ->where('is_active', true)
            ->orderBy('sort_order')
            ->orderBy('name')
            ->get(['id', 'name'])
            ->map(fn (self $type) => [
                'id' => $type->id,
                'value' => $type->name,
                'label' => $type->name,
            ])
            ->values()
            ->all();
    }

