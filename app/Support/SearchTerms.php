<?php

namespace App\Support;

/**
 * Монгол хэлний асуултаас хайх үгийн үндсийг ялгана.
 *
 * «Болдсайханы гаргасан бүх захирамжийн дугаар» гэх мэт асуултад
 * нэр нь харьяалахын тийн ялгалтай ордог тул шууд хайвал олдохгүй.
 * Тиймээс туслах үгсийг хаяж, нөхцөлийг нь таслаад үндсээр нь хайна.
 */
class SearchTerms
{
    /** Утга авч яваагүй, хайлтад саад болдог үгс. */
    private const STOP_WORDS = [
        'бүх', 'бүгд', 'бүгдийг', 'бүхий', 'нийт', 'нийтийг', 'хэдэн', 'хэд',
        'гаргасан', 'гарсан', 'гаргаж', 'гарга', 'гаргана', 'өгөөч', 'өгнө', 'өг',
        'харуул', 'харуулна', 'үзүүл', 'олж', 'ол', 'хай', 'хайж', 'жагсаа',
        'жагсаалт', 'жагсаалтыг', 'жагсаалтаас', 'мэдээлэл', 'мэдээллийг',
        'мэдээллээс', 'бүртгэл', 'бүртгэлийг', 'бүртгэлээс', 'бүртгэлт',
        'дугаар', 'дугаарыг', 'дугаарууд', 'дугаарын', 'дугаарлалт',
        'байна', 'байгаа', 'болон', 'тухай', 'талаар', 'энэ', 'тэр',
        'онд', 'оны', 'он', 'сард', 'сарын', 'сар', 'өдөр', 'өдрийн',
        'надад', 'над', 'миний', 'би', 'та', 'аас', 'ээс', 'уу', 'юу',
        'сүүлийн', 'хоног', 'хоногийн', 'юм', 'вэ', 'ямар', 'хэн', 'хаана',
    ];

    /**
     * Тийн ялгалын түгээмэл нөхцөлүүд — уртаас нь богино руу шалгана.
     *
     * @var list<string>
     */
    private const SUFFIXES = [
        'ийнхээ', 'ыныхаа', 'уудынхаа',
        'уудын', 'үүдийн', 'нуудын', 'нүүдийн',
        'ийнх', 'ыных', 'ийгээ', 'ыгаа',
        'аасаа', 'ээсээ', 'оосоо', 'өөсөө',
        'тайгаа', 'тэйгээ', 'тойгоо',
        'даа', 'дээ', 'доо', 'дөө',
        'ийн', 'ын', 'ний', 'ны', 'нь',
        'ийг', 'ыг', 'ийл',
        'аас', 'ээс', 'оос', 'өөс',
        'тай', 'тэй', 'той', 'төй',
        'руу', 'рүү', 'луу', 'лүү',
        'ууд', 'үүд',
        'аар', 'ээр', 'оор', 'өөр',
        'ад', 'эд', 'од', 'өд',
        'д', 'т', 'г',
    ];

    /**
     * Хайлтын үгсийн үндэс.
     *
     * @return list<string>
     */
    public static function tokens(?string $text, int $limit = 4): array
    {
        $words = preg_split(
            '/[^\p{L}\p{N}]+/u',
            mb_strtolower(trim((string) $text)),
            -1,
            PREG_SPLIT_NO_EMPTY,
        ) ?: [];

        $out = [];

        foreach ($words as $word) {
            if (in_array($word, self::STOP_WORDS, true)) {
                continue;
            }

            $stem = self::stem($word);

            // Хэт богино үндэс бүх мөрд таарах тул хэрэггүй.
            if (mb_strlen($stem) < 3 || in_array($stem, $out, true)) {
                continue;
            }

            $out[] = $stem;

            if (count($out) >= $limit) {
                break;
            }
        }

        return $out;
    }

    /**
     * Үгийн нөхцөлийг таслана.
     *
     * Богино үг (5 тэмдэгтээс бага) нь ихэвчлэн үндсээрээ байдаг тул
     * хөндөхгүй — «тушаал» гэдгийг «туш» болгочихвол утгагүй болно.
     */
    public static function stem(string $word): string
    {
        $word = mb_strtolower(trim($word));

        if (mb_strlen($word) < 5) {
            return $word;
        }

        foreach (self::SUFFIXES as $suffix) {
            if (! str_ends_with($word, $suffix)) {
                continue;
            }

            $stem = mb_substr($word, 0, mb_strlen($word) - mb_strlen($suffix));

            // Нөхцөлөө хассаны дараа дор хаяж 4 үсэг үлдэх ёстой.
            if (mb_strlen($stem) >= 4) {
                return $stem;
            }
        }

        return $word;
    }
}
