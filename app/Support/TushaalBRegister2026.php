    {
        $existing = Decree::query()
            ->where('kind', 'tushaal_b')
            ->pluck('number')
            ->map(fn (?string $number) => ltrim(trim((string) $number), '0') ?: '0')
            ->all();

        $directory = DirectoryNameResolver::directory();
        $added = [];

