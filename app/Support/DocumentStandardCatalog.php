    public static function sync(): void
    {
        $ids = [];
        foreach (self::categories() as $row) {
            $parentKey = $row['parent_key'] ?? null;
            unset($row['parent_key']);
            $category = DocumentStandardCategory::query()->updateOrCreate(
                ['key' => $row['key']],
                $row + ['parent_id' => null],
            );
            $ids[$category->key] = ['id' => $category->id, 'parent_key' => $parentKey];
        }

        foreach ($ids as $key => $meta) {
            if ($meta['parent_key'] === null) {
                continue;
            }
            DocumentStandardCategory::query()->where('key', $key)->update([
                'parent_id' => $ids[$meta['parent_key']]['id'] ?? null,
            ]);
        }

        foreach (self::articles() as $article) {
            $categoryId = DocumentStandardCategory::query()->where('key', $article['category'])->value('id');
            $slug = $article['slug'];
            unset($article['category'], $article['slug']);

            DocumentStandard::query()->firstOrCreate(
                ['slug' => $slug],
                $article + [
                    'category_id' => $categoryId,
                    'is_official' => true,
                    'sort_order' => $article['sort_order'] ?? 0,
                ],
            );
        }
    }

