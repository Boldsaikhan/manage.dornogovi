    public function looksLikeMojibake(string $value): bool
    {
        // CP1251-ийг Latin-1 гэж уншсан үед гарах өргөтгөсөн латин тэмдэгт.
        return (bool) preg_match('/[\x{00C0}-\x{00FF}]/u', $value);
    }

    public function fixMojibake(string $value): string
    {
        if (! $this->looksLikeMojibake($value)) {
            return $value;
        }

        $out = '';
        $buf = '';
        $len = mb_strlen($value, 'UTF-8');

        for ($i = 0; $i < $len; $i++) {
            $ch = mb_substr($value, $i, 1, 'UTF-8');
            $ord = mb_ord($ch, 'UTF-8');

            if ($ord !== false && $ord >= 128 && $ord <= 255) {
                $buf .= chr($ord);

                continue;
            }

            if ($buf !== '') {
                $out .= $this->decodeCp1251Buffer($buf);
                $buf = '';
            }

            $out .= $ch;
        }

        if ($buf !== '') {
            $out .= $this->decodeCp1251Buffer($buf);
        }

        return $this->fixMongolianLetters($out);
    }

    private function decodeCp1251Buffer(string $buf): string
    {
        $decoded = mb_convert_encoding($buf, 'UTF-8', 'Windows-1251');

        return is_string($decoded) ? $decoded : $buf;
    }

    /**
     * CP1251-д байхгүй ө/ү үсгүүд буруу тэмдэгтээр орсон байдаг.
     */
    private function fixMongolianLetters(string $value): string
    {
        return str_replace(
            ['є', 'ї', 'ў', 'º'],
            ['ө', 'ү', 'ү', 'ө'],
            $value,
        );
    }

    public function fingerprint(string $value): string
    {
        $value = $this->fixMojibake($value);
        $value = mb_strtolower($value, 'UTF-8');
        $value = str_replace(['ъ', '‟', '„', '“', '”', '"', "'", '«', '»'], ['ь', '', '', '', '', '', '', '', ''], $value);
        $value = preg_replace('/\s+/u', '', $value) ?? $value;
        $value = preg_replace('/[^\p{L}\p{N}]+/u', '', $value) ?? $value;

        return $value;
    }

    public function canonicalize(?string $value): ?string
    {
        if ($value === null) {
            return null;
        }

        $trimmed = trim($value);

        if ($trimmed === '') {
            return null;
        }

        $fixed = trim($this->fixMojibake($trimmed));
        // Хашилтыг бүгдийг нь хасна (trim charlist UTF-8-д кирилл эвддэг).
        $fixed = preg_replace('/["\'“”„‟«»]+/u', '', $fixed) ?? $fixed;
        $fixed = preg_replace('/\s+/u', ' ', trim($fixed)) ?? $fixed;
        $fixed = str_replace('ъ', 'ь', $fixed);

        $fp = $this->fingerprint($fixed);

        // Алтан гадас-ын урт тайлбартай хувилбарууд.
        if (
            str_starts_with($fp, 'алтангадас')
            || str_starts_with($fp, 'алангадас')
            || $fp === 'аго'
            || $fp === 'агоххм'
        ) {
            return 'Алтан гадас одон';
        }

        // Зөвхөн бүтэн нэр (оны тэмдэглэлгүй) дээр alias/fingerprint хэрэглэнэ.
        if ($this->isPlainAwardName($fixed)) {
            if (isset(self::ALIASES[$fp])) {
                return self::ALIASES[$fp];
            }

            if (isset(self::FINGERPRINT_CANONICAL[$fp])) {
                return self::FINGERPRINT_CANONICAL[$fp];
            }
        }

        return $fixed;
    }

    /**
     * «АГО-2018 он» гэх мэт оны тэмдэглэлтэй утгыг бүтэн солихгүй.
     */
    public function isPlainAwardName(string $value): bool
    {
        if (preg_match('/\d{4}/', $value) === 1) {
            return false;
        }

        if (str_contains($value, ',') || str_contains($value, '/')) {
            return false;
        }

        // Хэт урт тайлбар/тэмдэглэл.
        if (mb_strlen($value, 'UTF-8') > 80) {
            return false;
        }

        return true;
    }
